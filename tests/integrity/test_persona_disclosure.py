class TestN01ArXivValidationViaPersonaGuard:
    """Regression tests for N-01: PersonaGuard.guard() must propagate verified_arxivs
    to check_fabricated_citations() so fabricated arXiv IDs are caught in production paths.

    Previously PersonaGuard.__init__ did not accept/store verified_arxivs, so
    arXiv:9999.99999 would silently pass through guard() even when a real verified
    set was available.
    """

    def test_fabricated_arxiv_blocked_through_guard(self):
        """A fabricated arXiv ID is caught when PersonaGuard is given verified_arxivs."""
        guard = PersonaGuard(
            author_id="author_arxiv_test",
            author_name="Prof. ArXiv",
            verified_dois=set(),
            verified_arxivs={"2305.12345"},
        )
        # Text that would have silently passed before N-01 fix.
        bad_text = (
            "[AI Reviewer — Corpus Model] "
            "This review was generated by an AI Reviewer modeled from 5 public papers by Prof. ArXiv. "
            "This is not Prof. ArXiv's actual opinion or endorsement.\n\n"
            "See arXiv:9999.99999 for the foundational result."
        )
        result = guard.guard(bad_text, raise_on_violation=False)
        fabricated = [
            v for v in result.violations if v.violation == DisclosureViolation.FABRICATED_CITATION
        ]
        assert len(fabricated) >= 1, (
            "Fabricated arXiv ID arXiv:9999.99999 was not caught by PersonaGuard.guard(). "
            "N-01 fix may be missing."
        )
        assert any("9999.99999" in v.excerpt for v in fabricated)

    def test_verified_arxiv_passes_through_guard(self):
        """A verified arXiv ID does NOT raise a violation via PersonaGuard."""
        guard = PersonaGuard(
            author_id="author_arxiv_test",
            author_name="Prof. ArXiv",
            verified_dois=set(),
            verified_arxivs={"2305.12345"},
        )
        good_text = (
            "[AI Reviewer — Corpus Model] "
            "This review was generated by an AI Reviewer modeled from 5 public papers by Prof. ArXiv. "
            "This is not Prof. ArXiv's actual opinion or endorsement.\n\n"
            "See arXiv:2305.12345 for the foundational result."
        )
        result = guard.guard(good_text, raise_on_violation=False)
        fabricated = [
            v for v in result.violations if v.violation == DisclosureViolation.FABRICATED_CITATION
        ]
        assert fabricated == [], (
            f"Verified arXiv ID arXiv:2305.12345 was incorrectly flagged: {fabricated}"
        )

    def test_no_verified_arxivs_does_not_flag_any_arxiv(self):
        """When verified_arxivs is not provided, arXiv IDs are not individually validated."""
        guard = PersonaGuard(
            author_id="author_arxiv_test",
            author_name="Prof. ArXiv",
            verified_dois=set(),
            # verified_arxivs intentionally omitted (defaults to None)
        )
        text = (
            "[AI Reviewer — Corpus Model] "
            "This review was generated by an AI Reviewer modeled from 5 public papers by Prof. ArXiv. "
            "This is not Prof. ArXiv's actual opinion or endorsement.\n\n"
            "See arXiv:9999.99999 for background."
        )
        result = guard.guard(text, raise_on_violation=False)
        fabricated = [
            v for v in result.violations if v.violation == DisclosureViolation.FABRICATED_CITATION
        ]
        assert fabricated == [], (
            "ArXiv ID should not be flagged when verified_arxivs was not supplied to PersonaGuard."
        )

    def test_persona_spec_verified_arxivs_propagated(self):
        """PersonaSpec.verified_arxivs is propagated through ReviewPanel._review_single
        so a fabricated arXiv ID in the review is caught end-to-end."""
        from maglab.reviewer.corpus_rag import CorpusChunk, CorpusRAG
        from maglab.reviewer.panel import PersonaSpec, ReviewPanel

        rag = CorpusRAG()
        rag.add_chunk(
            CorpusChunk(
                chunk_id="chunk_001",
                author_id="arxiv_author",
                doi="10.1234/test.001",
                title="A Real Paper",
                text="spin Hall effect measurement",
            )
        )
        persona = PersonaSpec(
            author_id="arxiv_author",
            author_name="Prof. ArXiv Author",
            paper_count=1,
            verified_dois={"10.1234/test.001"},
            verified_arxivs={"2305.12345"},
        )

        fabricated_arxiv_text = (
            "[AI Reviewer — Corpus Model] "
            "This review was generated by an AI Reviewer modeled from 1 public papers by Prof. ArXiv Author. "
            "This is not Prof. ArXiv Author's actual opinion or endorsement.\n\n"
            "See arXiv:9999.99999 for a key result."
        )

        def fake_llm(p: PersonaSpec, manuscript: str, rag_results: list, rubric: object) -> str:
            return fabricated_arxiv_text

        panel = ReviewPanel(
            personas=[persona],
            corpus_rag=rag,
            llm_review_fn=fake_llm,
        )
        result = panel.review("Test manuscript.", raise_on_disclosure_violation=False)
        assert len(result.reviews) == 1
        pr = result.reviews[0]
        # disclosure_passed should be False because arXiv:9999.99999 is not in verified_arxivs
        assert not pr.disclosure_passed, (
            "ReviewPanel did not flag fabricated arXiv:9999.99999 even though "
            "PersonaSpec.verified_arxivs={'2305.12345'} was provided. "
            "PersonaSpec.verified_arxivs propagation may be missing."
        )


