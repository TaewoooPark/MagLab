VALID_DISCLOSURE_TEXT = (
    "[AI Reviewer — Corpus Model] "
    "This review was generated by an AI Reviewer modeled from 15 public papers by Prof. Smith. "
    "This is not Prof. Smith's actual opinion or endorsement. "
    "For manuscript preparation feedback only."
)


def _guard(author_id: str = "author_test") -> PersonaGuard:
    return PersonaGuard(
        author_id=author_id,
        author_name="Prof. Test",
        verified_dois={"10.1103/valid.001", "10.1103/valid.002"},
    )


# ---------------------------------------------------------------------------
# Safeguard ①: Missing disclosure label
# ---------------------------------------------------------------------------


class TestSafeguard1DisclosureLabel:
    """Safeguard ①: Missing disclosure label → blocked."""

    def test_missing_disclosure_label_detected(self):
        text = "This paper presents interesting results. The spin Hall angle was clearly measured."
        violations = check_disclosure_label(text)
        assert len(violations) >= 1
        assert violations[0].violation == DisclosureViolation.MISSING_DISCLOSURE_LABEL

    def test_valid_disclosure_label_passes(self):
        violations = check_disclosure_label(VALID_DISCLOSURE_TEXT)
        assert violations == []

    def test_persona_guard_blocks_missing_label(self):
        """PersonaGuard blocks text without the disclosure label."""
        guard = _guard()
        bad_text = "This is a novel paper."  # No label
        with pytest.raises(PersonaDisclosureError) as exc_info:
            guard.guard(bad_text)
        violations = exc_info.value.violations
        kinds = [v.violation for v in violations]
        assert DisclosureViolation.MISSING_DISCLOSURE_LABEL in kinds

    def test_build_disclosure_label_format(self):
        label = build_disclosure_label("Prof. Kim", 20)
        assert "AI Reviewer" in label
        assert "20 public papers" in label
        assert "actual opinion" in label or "endorsement" in label

    def test_add_disclosure_auto_prepend(self):
        """add_disclosure automatically prepends the label."""
        guard = _guard()
        text = "A novel paper."
        result = guard.add_disclosure(text, paper_count=10)
        assert "AI Reviewer" in result
        # Must not add duplicate labels
        result2 = guard.add_disclosure(result, paper_count=10)
        assert result2.count("AI Reviewer") == result.count("AI Reviewer")


