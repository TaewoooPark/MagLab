# Regression tests — F-02: DOI case normalization
# ---------------------------------------------------------------------------


class TestF02DOICaseNormalization:
    """Regression tests for F-02: DOI comparison must be case-insensitive.

    Previously, a mixed-case DOI in review text (e.g. from the paper itself)
    was falsely flagged as FABRICATED_CITATION even when the lowercase version
    existed in the verified set.
    """

    def test_mixed_case_doi_not_flagged_when_verified_lowercase(self):
        """Mixed-case DOI in text matches lowercase entry in verified_dois."""
        text = "See DOI: 10.1103/PhysRevLett.132.156801 for details."
        # verified_dois stores lowercase (as connectors normalise on ingest)
        verified = {"10.1103/physrevlett.132.156801"}
        violations = check_fabricated_citations(text, verified_dois=verified)
        fabricated = [
            v for v in violations if v.violation == DisclosureViolation.FABRICATED_CITATION
        ]
        assert fabricated == [], f"Mixed-case DOI falsely flagged as fabricated: {fabricated}"

    def test_uppercase_doi_not_flagged_when_verified_lowercase(self):
        """Fully uppercased DOI still matches lowercase entry."""
        text = "DOI: 10.1103/PHYSREVLETT.132.156801"
        verified = {"10.1103/physrevlett.132.156801"}
        violations = check_fabricated_citations(text, verified_dois=verified)
        fabricated = [
            v for v in violations if v.violation == DisclosureViolation.FABRICATED_CITATION
        ]
        assert fabricated == []

    def test_truly_unverified_doi_still_flagged(self):
        """A DOI genuinely absent from the verified set is still flagged."""
        text = "DOI: 10.1234/fake.999"
        verified = {"10.1103/physrevlett.132.156801"}
        violations = check_fabricated_citations(text, verified_dois=verified)
        fabricated = [
            v for v in violations if v.violation == DisclosureViolation.FABRICATED_CITATION
        ]
        assert len(fabricated) >= 1

    def test_persona_guard_mixed_case_doi_passes(self):
        """PersonaGuard does not block a mixed-case verified DOI."""
        guard = PersonaGuard(
            author_id="author_x",
            author_name="Prof. X",
            verified_dois={"10.1103/physrevlett.132.156801"},
        )
        compliant = (
            "[AI Reviewer — Corpus Model] "
            "This review was generated by an AI Reviewer modeled from 5 public papers by Prof. X. "
            "This is not Prof. X's actual opinion or endorsement.\n\n"
            "The result is supported by DOI: 10.1103/PhysRevLett.132.156801."
        )
        result = guard.guard(compliant, raise_on_violation=False)
        fabricated = [
            v for v in result.violations if v.violation == DisclosureViolation.FABRICATED_CITATION
        ]
        assert fabricated == [], result.summary()


