    def test_none_verified_dois_via_panel_does_not_flag_doi(self) -> None:
        """End-to-end: PersonaSpec with default verified_dois=None does not flag a
        review containing a real DOI, even through the full ReviewPanel path.
        """
        from maglab.reviewer.corpus_rag import CorpusChunk, CorpusRAG
        from maglab.reviewer.panel import PersonaSpec, ReviewPanel

        rag = CorpusRAG()
        rag.add_chunk(
            CorpusChunk(
                chunk_id="f01-chunk-001",
                author_id="f01_panel_author",
                doi="10.1103/physrevlett.100.096401",
                title="Spin Hall Paper",
                text="spin Hall effect measurement in Pt",
            )
        )

        # Default PersonaSpec — verified_dois=None, verified_arxivs=None
        persona = PersonaSpec(
            author_id="f01_panel_author",
            author_name="Prof. F01 Panel",
            paper_count=5,
            # Neither verified_dois nor verified_arxivs supplied
        )

        review_with_real_doi = (
            "[AI Reviewer — Corpus Model] "
            "This review was generated by an AI Reviewer modeled from 5 public papers by Prof. F01 Panel. "
            "This is not Prof. F01 Panel's actual opinion or endorsement.\n\n"
            "The spin Hall effect is documented in DOI: 10.1103/PhysRevLett.100.096401."
        )

        def fake_llm(p: PersonaSpec, manuscript: str, rag_results: list, rubric: object) -> str:
            return review_with_real_doi

        panel = ReviewPanel(
            personas=[persona],
            corpus_rag=rag,
            llm_review_fn=fake_llm,
        )
        result = panel.review("Test manuscript.", raise_on_disclosure_violation=False)
        pr = result.reviews[0]

        assert pr.disclosure_passed, (
            "ReviewPanel falsely blocked a valid review citing a real DOI when "
            "PersonaSpec uses default verified_dois=None. F-01 fix may be missing."
        )
